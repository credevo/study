"""
Polymer 연습용 파일을 브라우저에 전달하는 아주 간단한 웹 서버입니다.

브라우저는 index.html 같은 파일을 보여줄 때 웹 서버에 HTTP 요청을 보냅니다.
이 프로그램은 그 요청을 받아 현재 polymer 폴더에 있는 파일을 찾아서 전달합니다.

실행 방법:
    python server.py

브라우저 접속 주소:
    http://localhost:8080

종료 방법:
    이 프로그램을 실행한 터미널에서 Ctrl+C를 누릅니다.

이 파일은 Python에 기본으로 포함된 기능만 사용합니다.
따라서 Python만 설치되어 있으면 별도의 패키지를 설치할 필요가 없습니다.
"""


# ---------------------------------------------------------------------------
# 1. 필요한 기능 가져오기(import)
# ---------------------------------------------------------------------------

# Python에는 간단한 웹 서버를 만들 수 있는 http.server 모듈이 기본으로 들어 있습니다.
# `from 모듈 import 이름`은 해당 모듈에서 필요한 이름만 가져오는 문법입니다.
#
# ThreadingHTTPServer:
#   실제로 주소와 포트를 열고 브라우저의 HTTP 요청을 받는 서버 클래스입니다.
#   이름에 Threading이 붙은 이유는 여러 요청을 각각 나누어 처리할 수 있기 때문입니다.
#   HTML 페이지는 HTML, JavaScript, CSS 등을 연달아 요청할 수 있으므로 편리합니다.
#
# SimpleHTTPRequestHandler:
#   브라우저가 요청한 경로에 맞춰 폴더 안의 파일을 찾아 응답하는 클래스입니다.
#   예를 들어 브라우저가 `/index.html`을 요청하면 index.html 파일을 읽어 전달합니다.
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler

# pathlib는 파일과 폴더의 경로를 다루는 Python 기본 모듈입니다.
# 문자열을 직접 이어 붙이는 것보다 Windows와 Unix 계열 운영체제의 경로를
# 안전하고 읽기 쉽게 처리할 수 있습니다.
from pathlib import Path

# os는 운영체제와 관련된 기능을 제공하는 Python 기본 모듈입니다.
# 여기서는 프로그램의 현재 작업 폴더를 변경하는 chdir() 함수를 사용합니다.
import os


# ---------------------------------------------------------------------------
# 2. 웹 서버가 제공할 폴더 정하기
# ---------------------------------------------------------------------------

# `__file__`은 현재 실행 중인 이 Python 파일(server.py)의 경로를 담는 특별한 변수입니다.
#
# Path(__file__)
#   server.py의 경로 문자열을 pathlib의 Path 객체로 바꿉니다.
#
# .resolve()
#   상대 경로가 섞여 있더라도 완전한 절대 경로로 바꿉니다.
#   예: server.py -> D:\00000_DEV\study\polymer\server.py
#
# .parent
#   파일 경로에서 파일 이름을 제외한 부모 폴더를 가져옵니다.
#   결과적으로 PROJECT_DIR에는 polymer 폴더의 절대 경로가 저장됩니다.
#
# 변수 이름을 모두 대문자로 쓴 것은 이 값을 실행 중에 바꾸지 않는
# '상수처럼 사용하는 값'이라는 Python의 관례를 나타냅니다.
PROJECT_DIR = Path(__file__).resolve().parent

# 현재 작업 폴더를 server.py가 들어 있는 polymer 폴더로 변경합니다.
# SimpleHTTPRequestHandler는 기본적으로 '현재 작업 폴더'에서 파일을 찾습니다.
# 이 줄이 있기 때문에 다른 폴더에서 `python 경로/server.py` 형태로 실행하더라도
# 항상 polymer/index.html을 정확하게 제공할 수 있습니다.
os.chdir(PROJECT_DIR)


# ---------------------------------------------------------------------------
# 3. 서버 주소와 포트 설정하기
# ---------------------------------------------------------------------------

# 서버가 사용할 주소를 튜플(tuple) 형태로 저장합니다.
# 튜플은 여러 값을 하나로 묶으며 `(값1, 값2)`처럼 작성합니다.
#
# "127.0.0.1":
#   현재 내 컴퓨터 자신을 뜻하는 특별한 IP 주소입니다.
#   외부 컴퓨터에 공개하지 않고 이 PC에서만 접속할 수 있게 합니다.
#   브라우저 주소의 localhost도 일반적으로 127.0.0.1을 가리킵니다.
#
# 8080:
#   서버가 사용할 포트 번호입니다. 포트는 한 컴퓨터 안에서 여러 네트워크
#   프로그램을 구분하는 번호입니다. 브라우저 주소 뒤의 `:8080`이 이 값입니다.
address = ("127.0.0.1", 8080)


# ---------------------------------------------------------------------------
# 4. 사용자에게 실행 상태 알려주기
# ---------------------------------------------------------------------------

# print()는 괄호 안의 글자를 터미널에 출력하는 Python 기본 함수입니다.
# 첫 번째 문장은 브라우저에서 열 주소를, 두 번째 문장은 종료 방법을 알려줍니다.
print("Polymer test: http://localhost:8080")
print("Stop server: Ctrl+C")


# ---------------------------------------------------------------------------
# 5. 웹 서버 만들고 계속 실행하기
# ---------------------------------------------------------------------------

# ThreadingHTTPServer(address, SimpleHTTPRequestHandler)
#   위에서 정한 127.0.0.1:8080 주소에 웹 서버 객체를 만듭니다.
#   브라우저 요청이 들어오면 SimpleHTTPRequestHandler가 파일을 찾아 응답합니다.
#
# .serve_forever()
#   서버가 요청을 한 번만 받고 끝나지 않도록 계속 실행합니다.
#   이름은 '영원히 서비스한다'는 뜻이지만 Ctrl+C를 누르면 사용자가 종료할 수 있습니다.
#
# 전체 요청 흐름은 다음과 같습니다.
#   1. 브라우저에서 http://localhost:8080 접속
#   2. 브라우저가 127.0.0.1의 8080 포트로 index.html 요청
#   3. SimpleHTTPRequestHandler가 polymer 폴더에서 index.html 검색
#   4. 파일 내용을 HTTP 응답으로 브라우저에 전달
#   5. index.html이 요청하는 다른 파일도 같은 방식으로 전달
ThreadingHTTPServer(address, SimpleHTTPRequestHandler).serve_forever()
